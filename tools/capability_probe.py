def action_for(att):
    if att is None:
        return "Run the probe within the timebox."
    st, basis = att.get("http_status"), att.get("outcome_basis", "")
    if not att.get("sent") and basis.startswith("cost bound"):
        return "Stop. Review the cost bound and headroom before any further request."
    if not att.get("sent") and basis.startswith("preflight"):
        return "Record the missing documented values in the private config, then rerun preflight."
    if not att.get("sent"):
        return "Fix local network or TLS access (no request was sent), then run the probe again."
    if att.get("redirect"):
        return "Confirm the documented base URL and path (redirects are never followed), update the private config, then retry once."
    if att.get("timeout") or st is None:
        return "Check billing for a charge before any retry; retry once only if a duplicate charge fits the bound."
    if st in (401, 403):
        return "Check the key's access in the provider console without sharing the key, then retry once."
    if st == 404:
        return "Confirm the route and model ID from official documentation, update the private config, then retry once."
    if st in (400, 422):
        return "Read the sanitized error, correct the documented request parameter in the private config, then retry once."
    if st == 429 or (isinstance(st, int) and st >= 500):
        return "Wait, then retry once if the cost bound still fits."
    return "Review the stored reply; retry once only with a diagnosed cause."


