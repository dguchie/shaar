_TYPES = {"object": dict, "array": list, "string": str, "integer": int, "boolean": bool}


def check(schema, value, path="$"):
    t = schema.get("type")
    if t:
        ok = isinstance(value, _TYPES[t]) and not (t == "integer" and isinstance(value, bool))
        if not ok:
            return [f"{path}: expected {t}"]
    errs = []
    if "enum" in schema and value not in schema["enum"]:
        errs.append(f"{path}: value not allowed")
    if t == "string":
        if len(value) < schema.get("minLength", 0):
            errs.append(f"{path}: too short")
        if "maxLength" in schema and len(value) > schema["maxLength"]:
            errs.append(f"{path}: too long")
        if "pattern" in schema and not re.fullmatch(schema["pattern"], value):
            errs.append(f"{path}: does not match pattern")
    elif t == "integer":
        if "minimum" in schema and value < schema["minimum"]:
            errs.append(f"{path}: below minimum")
        if "maximum" in schema and value > schema["maximum"]:
            errs.append(f"{path}: above maximum")
    elif t == "array":
        if len(value) < schema.get("minItems", 0):
            errs.append(f"{path}: too few items")
        if "maxItems" in schema and len(value) > schema["maxItems"]:
            errs.append(f"{path}: too many items")
        for i, item in enumerate(value):
            errs += check(schema.get("items", {}), item, f"{path}[{i}]")
    elif t == "object":
        props = schema.get("properties", {})
        for k in schema.get("required", []):
            if k not in value:
                errs.append(f"{path}: missing required field '{k}'")
        if schema.get("additionalProperties") is False:
            for k in value:
                if k not in props:
                    errs.append(f"{path}: unexpected field '{k}'")
        for k, v in value.items():
            if k in props:
                errs += check(props[k], v, f"{path}.{k}")
    return errs


def parse_json_text(text):
    s = text.strip()
    fenced = False
    m = re.fullmatch(r"```(?:json)?[ \t]*\n(.*)\n```", s, re.S)
    if m:
        s, fenced = m.group(1).strip(), True
    try:
        return json.loads(s), fenced, None
    except ValueError as e:
        return None, fenced, f"invalid JSON: {getattr(e, 'msg', str(e))}"


def validate_text(probe, text):
    task = TASKS[PROBES[probe]["task"]]
    res = {"ok": False, "errors": [], "fence_stripped": False, "semantic_notes": []}
    if not isinstance(text, str) or not text.strip():
        res["errors"].append("empty reply")
        return res
    obj, fenced, perr = parse_json_text(text)
    res["fence_stripped"] = fenced
    if perr:
        res["errors"].append(perr)
        return res
    errs = check(task["schema"], obj)
    if errs:
        res["errors"] = errs[:20]
        return res
    res["ok"] = True
    res["semantic_notes"] = task["semantic"](obj)
    return res


def reply_text(probe, content, tool_calls):
    """Return (text to validate, what was checked, extraction error)."""
    if PROBES[probe]["feature"] == "tool":
        if not tool_calls:
            return None, "tool_call_arguments", "no tool call returned"
        if tool_calls[0].get("name") != TOOL_NAME:
            return None, "tool_call_arguments", "first tool call has an unexpected name"
        return tool_calls[0].get("arguments"), "tool_call_arguments", None
    return content, "message_content", None


def validate_reply(probe, content, tool_calls):
    text, checked, err = reply_text(probe, content, tool_calls)
    if err:
        res = {"ok": False, "errors": [err], "fence_stripped": False, "semantic_notes": []}
    else:
        res = validate_text(probe, text)
    res["checked"] = checked
    if tool_calls and len(tool_calls) > 1:
        res["semantic_notes"] = res["semantic_notes"] + [f"{len(tool_calls)} tool calls returned; first checked"]
    return res

