def cmd_run(args):
    probe, retry = args.probe, args.retry
    el = elapsed_min()
    if el is None:
        return refuse(f"timebox start not recorded in {TIMEBOX_FILE}")
    if el >= CALL_STOP_MIN:
        return refuse(f"elapsed {el} min is at or past minute {CALL_STOP_MIN}; no further requests")
    data = load_results()
    warned = [a["attempt_id"] for a in data["attempts"] if a.get("warnings")]
    if warned:
        return refuse(f"attempt {', '.join(warned)} recorded a cost or usage warning; no further requests")
    mine = [a for a in data["attempts"] if a["probe"] == probe]
    sent = [a for a in data["attempts"] if a.get("sent")]
    if retry is None:
        if any(a.get("sent") for a in mine):
            return refuse(f"{probe} already sent a request; a retry needs --retry with a diagnosis")
        if sum(1 for a in sent if a["kind"] == "primary") >= MAX_PRIMARY:
            return refuse("primary request limit reached")
        kind = "primary"
    else:
        if not any(a.get("sent") for a in mine):
            return refuse(f"{probe} has no sent request to retry; run it without --retry")
        if mine[-1]["outcome"] == "PASS":
            return refuse(f"{probe} last attempt passed; no retry")
        if sum(1 for a in sent if a["kind"] == "retry") >= MAX_RETRIES:
            return refuse("retry limit reached")
        kind = "retry"

    key = os.environ.get(KEY_ENV, "")
    scrub = Scrub(key)
    role, feature = PROBES[probe]["model"], PROBES[probe]["feature"]
    att = {"attempt_id": f"A{len(data['attempts']) + 1:02d}", "probe": probe, "kind": kind,
           "retry_reason": scrub(retry) if retry else None, "model_role": role,
           "elapsed_min": el, "sent": False}

    cfg = load_config()
    g, per, info = preflight(cfg)
    data["config_snapshot"] = public_config(cfg)
    if g or per[role]:
        att.update(outcome="BLOCKED", outcome_basis="preflight: " + "; ".join(g + per[role]))
        att["sanitized"] = scrub.changed
        data["attempts"].append(att)
        save_results(data)
        print(f"{att['attempt_id']} {probe} [{kind}] not sent -> BLOCKED | {att['outcome_basis']}")
        return 3

    mc, api = cfg["models"][role], cfg["api"]
    body = build_body(probe, mc, api)
    raw = json.dumps(body, sort_keys=True).encode("utf-8")
    endpoint = api["base_url"].rstrip("/") + api["chat_path"]
    bound = cost_bound(len(raw), mc)
    cap, done = info["effective_cap_usd"], committed_usd(data)
    att["request"] = {"endpoint": endpoint, "body": body, "body_bytes": len(raw)}
    att["cost_bound"] = bound
    if done + bound["usd"] > cap + 1e-9:
        att.update(outcome="BLOCKED", outcome_basis=(
            f"cost bound ${bound['usd']:.6f} exceeds remaining bounded headroom ${cap - done:.6f}; not sent"))
        att["sanitized"] = scrub.changed
        data["attempts"].append(att)
        save_results(data)
        print(f"{att['attempt_id']} {probe} [{kind}] not sent -> BLOCKED | {att['outcome_basis']}")
        return 3

    # Write-ahead: if the process stops mid-request, the ledger still shows a
    # possibly billed attempt at its full bound, and it cannot be re-sent as primary.
    att.update(sent=True, outcome="UNKNOWN",
               outcome_basis="request started; process ended before a reply was recorded; full bound counted")
    att["sanitized"] = scrub.changed
    data["attempts"].append(att)
    save_results(data)

    r = post(endpoint, raw, key)
    att.update(sent=r["sent"], http_status=r["status"], latency_ms=r["latency_ms"], timeout=r["timeout"],
               redirect=r["redirect"])
    if r["net_error"]:
        att["error"] = {"type": "network", "message": scrub(r["net_error"][:300])}
    obj = None
    if r["body"] is not None:
        try:
            obj = json.loads(r["body"].decode("utf-8", "replace"))
        except ValueError:
            obj = None
    if r["status"] == 200 and isinstance(obj, dict) and isinstance(obj.get("choices"), list) and obj["choices"]:
        view, dropped = response_view(obj, scrub)
        att["response"], att["dropped_fields"] = view, dropped
        att["validation"] = validate_reply(probe, view["content"], view["tool_calls"])
        att["usage_estimate_usd"] = usage_estimate(view["usage"], mc)
        att["reasoning_units_reported"] = find_num(view["usage"], "reasoning_tokens")
        warn = []
        u = view["usage"] or {}
        in_used = find_num(u, "prompt_tokens")
        in_used = find_num(u, "input_tokens") if in_used is None else in_used
        out_used = find_num(u, "completion_tokens")
        out_used = find_num(u, "output_tokens") if out_used is None else out_used
        rsn = att["reasoning_units_reported"]
        if att["usage_estimate_usd"] is None:
            warn.append("usage missing or not in a recognized form; cost data unavailable")
        if any(is_num(x) and x < 0 for x in (in_used, out_used, rsn)):
            warn.append("negative usage reported; cost data invalid")
        if is_num(in_used) and in_used > bound["in_tok_bound"]:
            warn.append("reported input units exceed the input bound; cost bounds are not reliable")
        if is_num(out_used) and out_used > bound["out_tok_bound"]:
            warn.append("reported output units exceed the output bound; cost bounds are not reliable")
        if is_num(rsn) and rsn > bound["out_tok_bound"]:
            warn.append("reported reasoning units exceed the output bound; cost bounds are not reliable")
        if mc["reasoning"] == "none" and is_num(rsn) and rsn > 0:
            warn.append("reasoning units reported for a model configured as non-reasoning; check the documented billing")
        if warn:
            att["warnings"] = warn
    elif r["status"] is not None and not r["redirect"]:
        att["error"] = error_view(obj, r["body"], scrub)
    att["outcome"], att["outcome_basis"] = classify(att, feature)
    att["sanitized"] = scrub.changed
    save_results(data)

    done = committed_usd(data)
    print(f"{att['attempt_id']} {probe} [{kind}] HTTP {r['status']} -> {att['outcome']} | {att['outcome_basis']} "
          f"| bound ${bound['usd']:.6f} | committed ${done:.6f} of ${cap:.2f} | elapsed {el} min")
    if "response" in att:
        resp = att["response"]
        shown = resp["content"] if feature != "tool" else json.dumps(resp["tool_calls"])
        print(f"  returned model: {resp['model']} | usage: {json.dumps(resp['usage'], sort_keys=True)}")
        print(f"  reply (first 200 chars): {(shown or '')[:200]!r}")
        if att["validation"]["errors"]:
            print("  validation errors: " + "; ".join(att["validation"]["errors"][:5]))
        if att["validation"]["semantic_notes"]:
            print("  notes: " + "; ".join(att["validation"]["semantic_notes"]))
    if "error" in att:
        print("  error (sanitized): " + json.dumps(att["error"], sort_keys=True)[:400])
    for w in att.get("warnings", []):
        print("  WARNING: " + w + ". All further requests are refused.")
    return 4 if att.get("warnings") else 0


