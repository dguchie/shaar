def preflight(cfg):
    g, per = [], {"spark": [], "wonder": []}
    info = {"effective_cap_usd": None, "out_bounds": {}, "decisions": []}
    if cfg is None:
        g.append("private config not found")
        return g, per, info
    ids = set()
    for i, d in enumerate(cfg.get("docs") or []):
        did = d.get("id")
        if not did or did in ids:
            g.append(f"docs[{i}]: id missing or duplicated")
            continue
        ids.add(did)
        if not d.get("title"):
            g.append(f"docs {did}: title missing")
        pr = url_problem(d.get("url"))
        if pr:
            g.append(f"docs {did}: url {pr}")
        if not DATE_RE.fullmatch(str(d.get("retrieved") or "")):
            g.append(f"docs {did}: retrieved date missing (YYYY-MM-DD)")
    api = cfg.get("api") or {}
    pr = url_problem(api.get("base_url"))
    if pr:
        g.append(f"api.base_url {pr}")
    if not str(api.get("chat_path") or "").startswith("/"):
        g.append("api.chat_path must start with /")
    if api.get("wire_format") != "openai_chat_completions":
        g.append("api.wire_format: only openai_chat_completions is implemented")
    if api.get("max_out_param") not in ("max_tokens", "max_completion_tokens"):
        g.append("api.max_out_param must be max_tokens or max_completion_tokens")
    if api.get("route_doc") not in ids:
        g.append("api.route_doc must name a docs id that confirms the route")
    for role in ("spark", "wonder"):
        mc = (cfg.get("models") or {}).get(role) or {}
        p = per[role]
        if not mc.get("id"):
            p.append("id missing")
        if mc.get("id_doc") not in ids:
            p.append("id_doc must name a docs id that confirms the model ID")
        for k in ("input_usd_per_mtok", "output_usd_per_mtok"):
            if not is_num(mc.get(k)) or mc.get(k) < 0:
                p.append(f"{k} missing")
        if mc.get("pricing_doc") not in ids:
            p.append("pricing_doc must name a docs id")
        rmo = mc.get("request_max_out")
        if not is_int(rmo) or not 1 <= rmo <= 32768:
            p.append("request_max_out must be an integer from 1 to 32768")
        dmo = mc.get("documented_max_out")
        if dmo is not None:
            if not is_int(dmo):
                p.append("documented_max_out must be an integer or null")
            elif is_int(rmo) and rmo > dmo:
                p.append("request_max_out exceeds documented_max_out")
            if mc.get("limits_doc") not in ids:
                p.append("limits_doc must name a docs id when documented_max_out is set")
        if mc.get("reasoning") not in REASONING_VALUES:
            p.append("reasoning must be none, billed_as_output or not_billed (otherwise cost cannot be bounded)")
        elif mc.get("reasoning_doc") not in ids:
            p.append("reasoning_doc must name a docs id")
        if mc.get("reasoning") == "billed_as_output" and mc.get("limits_doc") not in ids:
            p.append("limits_doc must name a docs id when reasoning is billed as output")
        if mc.get("reasoning") == "billed_as_output" and out_bound(mc) is None:
            p.append(REASONING_CAP_BLOCKER)
            info["decisions"].append(f"{role}: {REASONING_CAP_BLOCKER}")
        if not p:
            b = out_bound(mc)
            if b is None:
                p.append("reasoning output is not bounded by documented limits")
            info["out_bounds"][role] = b
    b = cfg.get("budget") or {}
    rem, cap, reserve = b.get("remaining_usd_billing_console"), b.get("spike_cap_usd"), b.get("final_reserve_usd")
    if not is_num(cap) or not is_num(reserve):
        g.append("budget.spike_cap_usd and budget.final_reserve_usd must be numbers")
    elif not is_num(rem):
        g.append("budget.remaining_usd_billing_console missing (billing-console observation)")
    else:
        eff = min(cap, rem - reserve)
        if eff <= 0:
            g.append("no headroom above the final-run reserve")
        else:
            info["effective_cap_usd"] = round(eff, 6)
    key = os.environ.get(KEY_ENV, "")
    if not key:
        g.append(f"{KEY_ENV} not set")
    elif re.search(r"\s", key):
        g.append(f"{KEY_ENV} contains whitespace")
    return g, per, info


def public_config(cfg):
    if cfg is None:
        return None
    api = cfg.get("api") or {}
    models = {}
    for role in ("spark", "wonder"):
        mc = (cfg.get("models") or {}).get(role) or {}
        models[role] = {k: mc.get(k) for k in (
            "id", "id_doc", "input_usd_per_mtok", "output_usd_per_mtok", "pricing_doc",
            "request_max_out", "documented_max_out", "limits_doc", "reasoning",
            "reasoning_doc", "reasoning_inside_max_out", "documented_max_reasoning",
            "preview_status", "preview_doc")}
    b = cfg.get("budget") or {}
    return {
        "api": {k: api.get(k) for k in ("base_url", "chat_path", "wire_format", "max_out_param", "route_doc")},
        "docs": [{k: d.get(k) for k in ("id", "title", "url", "retrieved")} for d in cfg.get("docs") or []],
        "models": models,
        "budget": {k: b.get(k) for k in (
            "credit_usd_billing_console", "remaining_usd_billing_console", "spike_cap_usd",
            "final_reserve_usd", "observed_charges_usd")},
        "status": cfg.get("status"),
    }

