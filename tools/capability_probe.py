def is_num(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def is_int(v):
    return isinstance(v, int) and not isinstance(v, bool)


def url_problem(u):
    if not isinstance(u, str) or not u:
        return "missing"
    p = urllib.parse.urlsplit(u)
    if p.scheme != "https":
        return "is not https"
    if p.query or p.fragment or "?" in u or "#" in u:
        return "has a query string or fragment"
    if "@" in p.netloc:
        return "contains credentials"
    if not p.hostname:
        return "has no host"
    return None


def out_bound(mc):
    """Largest number of billable output units one request can produce, or None."""
    r, rmo = mc.get("reasoning"), mc.get("request_max_out")
    if not is_int(rmo):
        return None
    if r in ("none", "not_billed"):
        return rmo
    if r == "billed_as_output":
        if mc.get("reasoning_inside_max_out") is True:
            return rmo
        dmr = mc.get("documented_max_reasoning")
        if is_int(dmr) and dmr >= 0:
            return rmo + dmr
    return None


def cost_bound(body_bytes, mc):
    in_b = body_bytes + INPUT_MARGIN  # assumes at least one byte of body per input unit
    out_b = out_bound(mc)
    usd = in_b * mc["input_usd_per_mtok"] / 1e6 + out_b * mc["output_usd_per_mtok"] / 1e6
    # round up to the next millionth of a dollar (after removing float noise)
    return {"in_tok_bound": in_b, "out_tok_bound": out_b, "usd": math.ceil(round(usd * 1e6, 3)) / 1e6}


