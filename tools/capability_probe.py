def semantic_constraint_map(obj):
    notes = []
    ids = [c["id"] for c in obj["constraints"]]
    if len(set(ids)) != len(ids):
        notes.append("duplicate constraint ids")
    cited = {s for c in obj["constraints"] for s in c["sources"]}
    missing = sorted({"S1", "S2", "S3"} - cited)
    if missing:
        notes.append("source lines not cited: " + ", ".join(missing))
    return notes


def semantic_repair(obj):
    notes = []
    if obj["line"] != 2:
        notes.append("line is not the faulty line 2")
    if " ".join(obj["replacement"].split()) not in ("return a + b", "return b + a"):
        notes.append("replacement is not one of the expected fixes")
    return notes


