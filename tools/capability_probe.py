def die(msg, code=1):
    print("ERROR: " + msg, file=sys.stderr)
    sys.exit(code)


def load_results():
    if not RESULTS.exists():
        return {"format": FORMAT, "attempts": [], "preflight": None,
                "config_snapshot": None, "validator_checks": None}
    try:
        data = json.loads(RESULTS.read_text())
    except ValueError:
        die(f"{RESULTS_REL} exists but is not valid JSON; stopping")
    if data.get("format") != FORMAT:
        die(f"{RESULTS_REL} exists but was not written by this probe; stopping")
    return data


def save_results(data):
    RESULTS.parent.mkdir(parents=True, exist_ok=True)
    tmp = RESULTS.with_name(RESULTS.name + ".tmp")
    tmp.write_text(json.dumps(data, sort_keys=True, indent=2, ensure_ascii=False) + "\n")
    os.replace(tmp, RESULTS)


def elapsed_min():
    try:
        start = int(TIMEBOX_FILE.read_text().strip())
    except (OSError, ValueError):
        return None
    return round((time.time() - start) / 60, 1)


def committed_usd(data):
    return round(sum(a["cost_bound"]["usd"] for a in data["attempts"]
                     if a.get("sent") and a.get("cost_bound")), 6)

